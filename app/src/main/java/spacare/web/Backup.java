package spacare.web;

import java.nio.file.*;
import java.sql.*;
import java.time.*;

/** H2 BACKUP creates a consistent snapshot while the application is running. */
public final class Backup {

  static LocalDate lastBackup;

  public static Path create(Connection c) throws Exception {
    if (
      !Database.url.startsWith("jdbc:h2:file:")
    ) throw new IllegalArgumentException("Sao lưu cần chế độ lưu file");
    Path directory = Path.of(
      System.getenv().getOrDefault("SPACARE_BACKUP_DIR", "./backups")
    ).toAbsolutePath();
    Files.createDirectories(directory);
    Path target = directory.resolve(
      "spacare-" + LocalDateTime.now().toString().replace(':', '-') + ".zip"
    );
    // Path is generated by the server, not supplied by the HTTP request.
    try (Statement s = c.createStatement()) {
      s.execute("BACKUP TO '" + target.toString().replace("'", "''") + "'");
    }
    return target;
  }

  public static void daily(Connection c) throws Exception {
    if (
      Database.url.startsWith("jdbc:h2:file:") &&
      !LocalDate.now().equals(lastBackup)
    ) {
      create(c);
      lastBackup = LocalDate.now();
    }
  }
}
